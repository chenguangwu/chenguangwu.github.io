def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    if not (a.dry_run or a.apply):
        print("请指定 --dry-run 或 --apply")
        return 2

    dd = json.load(open(DD, encoding="utf-8"))
    added = 0
    for slug, fields in F.items():
        key = "finance/" + slug
        if key not in dd:
            print("!! 缺条目:", key)
            continue
        for k, v in fields.items():
            dd[key][k] = v
        added += 1
    print("待写入工具数: %d；字段: %s" % (added, " ".join(sorted({k for f in F.values() for k in f}))))
    bad = [k for k, f in F.items() if len(f.get("features", [])) != 4 or len(f.get("steps", [])) != 5 or len(f.get("tips", [])) != 4]
    if bad:
        print("!! 条数不符合 features=4/steps=5/tips=4 的:", bad)

    if a.dry_run:
        for key in list(F)[:2]:
            print("\n预览 finance/%s => %s" % (key, json.dumps({k: F[key][k] for k in ("features", "steps", "tips")}, ensure_ascii=False)[:400]))
        return 0

    json.dump(dd, open(DD, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("已写入 content_deepdive.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

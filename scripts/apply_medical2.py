def main():
    with open(PATH, encoding="utf-8") as f:
        d = json.load(f)
    before = len(d)
    cliche = 0
    for k, v in REAL.items():
        if k not in d:
            raise SystemExit("MISSING KEY: " + k)
        # 残留英文变量名/模板检测
        blob = json.dumps(d[k], ensure_ascii=False)
        for bad in ["建立输入边界", "拆分归因", "样本验证", "口径漂移", "经验复用", "Iv Drip Speed", "Bed Occupancy", "Medical Abbrev", "Surgery Duration", "Drug Expiry", "Exposure Triangle"]:
            if bad in blob:
                cliche += 1
        d[k]["title"] = v["title"]
        d[k]["scenarios"] = v["scenarios"]
        d[k]["examples"] = v["examples"]
        d[k]["faqs"] = v["faqs"]
    # 写回（indent=1，与仓库一致）
    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=1, separators=(",", ": "))
    after = len(d)
    print("keys:", after, "conserved=", before == after)
    print("residual cliche in these keys:", cliche)
    ok = sum(1 for k in REAL if d[k]["title"] == REAL[k]["title"])
    print("realized keys:", ok, "/", len(REAL))

if __name__ == "__main__":
    main()

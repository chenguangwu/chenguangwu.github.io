def main():
    with open(PATH, encoding="utf-8") as f:
        d = json.load(f, strict=False)
    n_upd = 0
    n_miss = 0
    n_none = 0
    for slug, v in ENT.items():
        key = "engineering/" + slug
        if key not in d:
            n_miss += 1
            print("MISSING:", key)
            continue
        e = d[key]
        e["summary"] = v["summary"]
        e["scenarios"] = list(v["scenarios"])
        e["examples"] = [{"title": x["title"], "body": x["body"]} for x in v["examples"]]
        e["faqs"] = [{"q": x["q"], "a": x["a"]} for x in v["faqs"]]
        if not (e.get("summary") or "").strip():
            n_none += 1
        n_upd += 1
    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
    print("updated:", n_upd, "missing:", n_miss, "summary_none:", n_none)


if __name__ == "__main__":
    main()

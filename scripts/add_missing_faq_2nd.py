def main(apply=False):
    DD = json.load(open(DD_PATH, encoding='utf-8'))
    n_skipped = n_done = 0
    for k, faq in FAQ2.items():
        v = DD.get(k)
        if not v:
            print('  !! 缺键 %s' % k)
            continue
        faqs = v.get('faqs') or []
        if len(faqs) >= 2:
            n_skipped += 1
            continue
        faqs.append(dict(faq))
        v['faqs'] = faqs
        n_done += 1
    print('补第 2 条 FAQ：%d 条；已达标跳过 %d 条' % (n_done, n_skipped))
    if apply:
        cur = open(DD_PATH, encoding='utf-8').read()
        new = json.dumps(DD, ensure_ascii=False, indent=1)
        if cur.endswith('\n'):
            new += '\n'
        open(DD_PATH, 'w', encoding='utf-8').write(new)
        print('已落盘')
    else:
        print('（dry-run）')


if __name__ == '__main__':
    main('--apply' in sys.argv)

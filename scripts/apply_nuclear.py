def main():
    if not os.path.exists(JSON_PATH):
        print('JSON not found:', JSON_PATH); sys.exit(1)
    with open(JSON_PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)
    changed = 0
    for slug, info in KB.items():
        blob = json.dumps(info, ensure_ascii=False)
        if BAD_RE.search(blob):
            print('SELF-CHECK FAIL placeholder in', slug); sys.exit(1)
        for fld in ('title', 'scenarios', 'examples', 'faqs'):
            if fld not in info:
                print('SELF-CHECK FAIL missing', fld, 'in', slug); sys.exit(1)
        if slug not in data:
            data[slug] = {}
        if data[slug] != info:
            data[slug] = info
            changed += 1
        else:
            print('  unchanged:', slug)
    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('KB entries:', len(KB), 'changed:', changed)

if __name__ == '__main__':
    main()

def main():
    with open(SRC, encoding="utf-8") as f:
        data = json.load(f)
    before = len(data)
    assert before == 5022, "键数守恒失败: 期望 5022, 实际 %d" % before
    for k in TARGET_KEYS:
        assert k in data, "目标键缺失: %s" % k
        data[k] = NEW[k]
    with open(SRC, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1, separators=(",", ": "))
    after = len(data)
    assert after == 5022, "写回后键数异常: %d" % after
    print("OK accessibility 真实化 %d 键 | 总键数 %d（守恒）" % (len(TARGET_KEYS), after))

if __name__ == "__main__":
    main()

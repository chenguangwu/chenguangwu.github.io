def main():
    with open(SRC, 'r', encoding='utf-8') as f:
        data = json.load(f)
    before = len(data)
    missing = [k for k in REPL if k not in data]
    if missing:
        print("ERROR missing keys:", missing); sys.exit(1)
    for k, v in REPL.items():
        data[k] = v
    assert len(data) == before, f"键数变化: {before} -> {len(data)}"
    assert len(data) == 5022, f"键数不为 5022: {len(data)}"
    with open(SRC, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write('\n')
    if os.path.exists(DET):
        import subprocess
        r = subprocess.run([sys.executable, DET, '--cat', 'misc2'],
                           cwd=ROOT, capture_output=True, text=True)
        if r.returncode != 0:
            print("WARN detect_placeholders 命中残留（exit!=0），请核查：")
            print(r.stdout[-1500:])
        else:
            print("OK detect_placeholders(misc2) 已无占位命中")
    print(f"OK: misc2 10 条 deep-dive 已真实化，键数守恒 = {len(data)}")

if __name__ == '__main__':
    main()

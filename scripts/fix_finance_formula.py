def main():
    apply = '--apply' in sys.argv
    stat = {}
    for slug in MAP:
        r = process(slug, apply)
        stat[r] = stat.get(r, 0) + 1
        if r not in ('NOCHANGE',) and not apply:
            print('  [%s] %s' % (r, slug))
    print('\n模式: %s | MAP 条目 %d | %s' % ('apply' if apply else 'dry-run', len(MAP), stat))
    return 0


if __name__ == '__main__':
    sys.exit(main())

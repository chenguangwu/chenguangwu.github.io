def main():
    with open(PATH, 'r', encoding='utf-8') as f:
        obj = json.load(f)
    missing = [k for k in DATA if k not in obj]
    if missing:
        raise SystemExit("content_deepdive.json 缺少键: %s" % missing)
    for k, v in DATA.items():
        obj[k] = v
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)
    print("content_deepdive.json 已真实化 %d 个 exhibition 键" % len(DATA))


if __name__ == '__main__':
    main()

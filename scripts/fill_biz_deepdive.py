def main():
    dd = json.load(open(PATH, encoding='utf-8'))
    # 清理孤儿键（页面已不存在的下架工具）
    for k in [k for k in dd if k.startswith(IND + '/')]:
        slug = k.split('/', 1)[1]
        if not os.path.exists(os.path.join(ROOT, 'tools', IND, slug + '.html')):
            del dd[k]
            print('删除孤儿键:', k)

    for slug, entry in D.items():
        blob = json.dumps(entry, ensure_ascii=False)
        if FP.search(blob):
            raise SystemExit('套话命中 slug=%s' % slug)
        if len(entry['scenarios']) < 2 or len(entry['examples']) < 1 or len(entry['faqs']) < 2:
            raise SystemExit('条目不达 §4.5 下限 slug=%s' % slug)
        key = IND + '/' + slug
        dd[key] = entry

    json.dump(dd, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('OK 写入/更新 biz deep-dive 条目=%d' % len(D))


if __name__ == '__main__':
    main()

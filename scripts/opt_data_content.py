def main():
    if not os.path.exists(JSON_PATH):
        print('ERROR: %s 不存在' % JSON_PATH); sys.exit(1)
    d = json.load(open(JSON_PATH, encoding='utf-8'))
    cnt = 0; skip = 0
    for k, v in DATA.items():
        key = 'data/' + k
        if key not in d:
            print('  WARN 未找到 key:', key); continue
        old = d[key]
        if old.get('summary') and '先统一输入单位与口径' not in ' '.join(old.get('scenarios', [])):
            skip += 1; continue
        d[key] = {
            'summary': v['summary'],
            'scenarios': v['scenarios'],
            'examples': [{'title': v['example']['title'], 'body': v['example']['body']}],
            'faqs': v['faqs'],
        }
        cnt += 1
    json.dump(d, open(JSON_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print('data 真实化完成：更新 %d 个 key，跳过 %d 个（已真实）' % (cnt, skip))

if __name__ == '__main__':
    main()

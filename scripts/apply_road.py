def main():
    d = load()
    before = len(d)
    if before != EXPECT_KEYS:
        print(f"[ERR] 键数异常 before={before}, 期望 {EXPECT_KEYS}")
        sys.exit(1)
    replaced = []
    for k, v in NEW.items():
        if k not in d:
            print(f"[ERR] 缺失键 {k}")
            sys.exit(1)
        d[k] = v
        replaced.append(k)
    after = len(d)
    if after != EXPECT_KEYS:
        print(f"[ERR] 键数异常 after={after}, 期望 {EXPECT_KEYS}")
        sys.exit(1)
    save(d)
    print(f"[OK] 替换 {len(replaced)} 条 road deep-dive，键数守恒 {before} -> {after}")
    for k in replaced:
        print("  - " + k)

if __name__ == "__main__":
    main()

def main(apply=False):
    DD = json.load(open(DD_PATH, encoding='utf-8'))
    n = 0
    for k, v in DATA.items():
        if k not in DD:
            print('  !! 缺键 %s' % k)
            continue
        DD[k]['title'] = v['title']
        DD[k]['scenarios'] = v['scenarios']
        DD[k]['examples'] = v['examples']
        DD[k]['faqs'] = v['faqs']
        n += 1
    print('改写 %d 条' % n)
    if apply:
        cur = open(DD_PATH, encoding='utf-8').read()
        new = json.dumps(DD, ensure_ascii=False, indent=1)
        if cur.endswith('\n'):
            new += '\n'
        open(DD_PATH, 'w', encoding='utf-8').write(new)
        print('已落盘')
    else:
        print('（dry-run）')


if __name__ == '__main__':
    main('--apply' in sys.argv)

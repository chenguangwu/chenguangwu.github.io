def main():
    if not os.path.exists(JSON_PATH):
        print("ERROR: content_deepdive.json not found")
        sys.exit(1)
    with open(JSON_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    changed = 0
    for slug, new in KB.items():
        # 自检：KB 自身不能含占位
        blob = json.dumps(new, ensure_ascii=False)
        if BAD_RE.search(blob):
            print("SELF-CHECK FAILED for", slug)
            sys.exit(1)
        if slug not in data:
            print("WARN: slug not in json, skip:", slug)
            continue
        if data[slug] != new:
            data[slug] = new
            changed += 1

    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")

    print("KB entries:", len(KB), "changed:", changed)


if __name__ == "__main__":
    main()

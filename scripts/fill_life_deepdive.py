def main():
    dd = json.load(open(PATH, encoding='utf-8'))

    # 清理孤儿键（life 目录下已无对应页面的条目）
    life_slugs = {os.path.basename(f)[:-5] for f in os.listdir(os.path.join(ROOT, 'tools', IND))
                  if f.endswith('.html') and f != 'index.html'}
    removed = 0
    for k in [k for k in dd if k.startswith(IND + '/')]:
        if k.split('/', 1)[1] not in life_slugs:
            del dd[k]
            removed += 1
            print('删除孤儿键:', k)

    added = appended = 0
    for slug in sorted(life_slugs):
        key = IND + '/' + slug
        if slug in FULL:
            e = FULL[slug]
            blob = json.dumps(e, ensure_ascii=False)
            if FP.search(blob):
                raise SystemExit('套话命中 slug=%s' % slug)
            if len(e['scenarios']) < 2 or len(e['examples']) < 1 or len(e['faqs']) < 2:
                raise SystemExit('条目不达 §4.5 下限 slug=%s' % slug)
            dd[key] = e
            added += 1
        elif slug in ADD:
            s2, f2q, f2a = ADD[slug]
            cur = dd.get(key)
            if not isinstance(cur, dict):
                raise SystemExit('ADD 条目缺少现有 deep-dive: %s' % slug)
            sc = cur.setdefault('scenarios', [])
            fa = cur.setdefault('faqs', [])
            if s2 not in sc:
                sc.append(s2)
            if not any(f.get('q') == f2q for f in fa):
                fa.append({'q': f2q, 'a': f2a})
            appended += 1

    # 全局校验：所有 life 页须达 §4.5
    bad = []
    for slug in sorted(life_slugs):
        e = dd.get(IND + '/' + slug, {})
        sc = e.get('scenarios') or []
        fa = e.get('faqs') or []
        ex = e.get('examples') or []
        if len(sc) < 2 or len(ex) < 1 or len(fa) < 2 or FP.search(json.dumps(e, ensure_ascii=False)):
            bad.append((slug, len(sc), len(ex), len(fa)))
    if bad:
        raise SystemExit('未达标: %s' % bad)

    json.dump(dd, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('OK 删除孤儿=%d 写入完整条目=%d 追加场景/FAQ=%d' % (removed, added, appended))


if __name__ == '__main__':
    main()

def main():
    with open(JSON_PATH, encoding="utf-8") as f:
        data = json.load(f)

    # 覆盖所有 legal/ 现有 key
    changed = 0
    missing = []
    for slug in sorted(KB.keys()):
        if slug not in data:
            missing.append(slug)
            continue
        new = KB[slug]
        # 自检：不含占位短语
        blob = json.dumps(new, ensure_ascii=False)
        if BAD_RE.search(blob):
            print("SELF-CHECK FAIL at", slug)
            sys.exit(1)
        if data[slug] != new:
            data[slug] = new
            changed += 1

    # 同时处理 JSON 中存在的 legal/ key 但 KB 未列（理论上无）
    for k in list(data.keys()):
        if k.startswith("legal/") and k not in KB:
            print("WARN uncovered legal key:", k)

    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")

    print("KB entries:", len(KB), " changed:", changed)
    if missing:
        print("MISSING in json:", missing)


if __name__ == "__main__":
    main()

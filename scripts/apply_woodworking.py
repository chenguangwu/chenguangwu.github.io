ENG_VAR = ["Angle Cut", "Board Feet", "Moisture Content", "Mortise Size", "Wood Screws"]


def main():
    data = json.load(open(PATH, encoding="utf-8"))
    before = len(data)
    residual = []
    for k, v in NEW.items():
        assert k in data, "missing key: " + k
        data[k] = v
    # 残留英文变量名检查
    blob = json.dumps(data, ensure_ascii=False)
    for ev in ENG_VAR:
        if ev in blob:
            residual.append(ev)
    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    after = len(data)
    print("OK 已真实化 %d 个键，键数守恒=%d" % (len(NEW), after))
    print("keys:", after, " 变化:", after - before)
    for k in NEW:
        print(k, "OK")
    print("残留英文变量名:", residual)


if __name__ == "__main__":
    main()

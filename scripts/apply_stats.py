def main():
    with open(JSON_PATH, encoding="utf-8") as f:
        data = json.load(f)
    before = len(data)
    for k in KEYS:
        if k not in data:
            print("MISSING KEY:", k, file=sys.stderr)
            sys.exit(1)
        data[k] = CONTENT[k]
    # 键数守恒校验
    assert len(data) == before, "键数发生变化: %d -> %d" % (before, len(data))
    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1, separators=(",", ": "))
    print("OK 已真实化 %d 个键，键数守恒=%d" % (len(KEYS), len(data)))

if __name__ == "__main__":
    main()

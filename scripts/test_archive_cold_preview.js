#!/usr/bin/env node
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { JSDOM } = require('jsdom');
const page = fs.readFileSync(path.join(__dirname, '../tools/clinical-nursing/reminder-time-1.html'), 'utf8');
const script = [...page.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1]).find(s => s.includes('var PHASE ='));
const dom = new JSDOM(page.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, ''), { runScripts: 'dangerously', url: 'https://example.test/' });
const { window } = dom;
const doc = window.document;
window.ToolBox = { showToast() {}, escHtml: value => String(value) };
window.i18nText = () => '';
window.confirm = () => true;
window.eval(script);
const set = (id, value) => { const el = doc.getElementById(id); el.value = value; el.dispatchEvent(new window.Event('input', { bubbles: true })); };
set('coldDur', '15');
assert.strictEqual(doc.getElementById('timerText').textContent, '15:00', '待开始时修改应更新计时器');
assert(doc.getElementById('planPreview').textContent.includes('15 分钟'));
set('restDur', '40');
set('checkDur', '4');
assert(doc.getElementById('planPreview').textContent.includes('40 分钟'));
assert(doc.getElementById('planPreview').textContent.includes('4 分钟'));
window.startSession();
window.tick();
const before = doc.getElementById('timerText').textContent;
set('coldDur', '10');
assert.strictEqual(doc.getElementById('timerText').textContent, before, '计时中不得重置当前会话');
window.togglePause();
set('checkDur', '3');
assert.strictEqual(doc.getElementById('timerText').textContent, before, '暂停时不得重置当前会话');
window.stopSession();
assert.strictEqual(doc.getElementById('timerText').textContent, '10:00', '结束后显示新的冷敷时长');
console.log('PASS 冷敷方案预览、计时与暂停');
window.close();

def _norm(v):
    """把 scenarios 的 dict 列表归一化为 _build.py / gen_guide_pages 期望的字符串列表。"""
    sc = v.get('scenarios') or []
    if sc and isinstance(sc[0], dict):
        nv = dict(v)
        nv['scenarios'] = ['%s：%s' % (s.get('title', ''), s.get('body', '')) for s in sc]
        return nv
    return v


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--apply":
        if not os.path.exists(DD_PATH):
            print("ERROR: %s not found" % DD_PATH)
            return 1
        with open(DD_PATH, encoding="utf-8") as f:
            data = json.load(f)
        n = 0
        for k, v in CONTENT.items():
            data[k] = _norm(v)
            n += 1
        with open(DD_PATH, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
        print("Applied %d deep-dive entries for health batch5" % n)
        return 0
    else:
        print("DRY: would write %d entries:" % len(CONTENT))
        for k in CONTENT:
            print("  ", k)
        return 0


if __name__ == "__main__":
    raise SystemExit(main())

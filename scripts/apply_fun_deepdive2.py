def main():
    apply = '--apply' in sys.argv
    d = json.load(open(SRC, encoding='utf-8'))
    n_ok = 0
    for k, v in CONTENT.items():
        # 数据源无条目时直接新增（如 daily-riddle），有则覆盖
        assert len(v['scenarios']) == 3 and len(v['examples']) == 2 and len(v['faqs']) == 2, f'{k} 结构不符'
        if not any(re.search(r'[\d０-９]', x['body']) for x in v['examples']):
            print('WARNING 缺数字(仍写入):', k)
        d[k] = v
        n_ok += 1
        if apply:
            # 增量落盘：每更新一条立即写盘，避免单条异常丢失整批进度
            json.dump(d, open(SRC, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('新增/更新', k)
    print('完成', n_ok, '条')
    if not apply:
        print('（dry-run，未写盘）')


if __name__ == '__main__':
    main()

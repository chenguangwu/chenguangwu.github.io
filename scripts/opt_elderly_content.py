def setk(slug, summary, sc, ex, faqs):
    key = "elderly/" + slug
    assert key in data, "missing key: " + key
    data[key] = dict(
        summary=summary,
        scenarios=sc,
        example=ex,
        faqs=[dict(q=q, a=a + DIS) for q, a in faqs],
    )



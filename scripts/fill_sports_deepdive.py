def main():
    dd = json.load(open(PATH, encoding='utf-8'))
    slugs = sorted(os.path.basename(f)[:-5] for f in
                   glob.glob(os.path.join(ROOT, 'tools', 'sports', '*.html'))
                   if not f.endswith('index.html'))
    missing = [s for s in slugs if ('sports/' + s) not in dd]
    if missing:
        raise SystemExit('sports 条目缺失: ' + str(missing))
    key_missing = [s for s in slugs if s not in D]
    if key_missing:
        raise SystemExit('DICT 缺键(待补内容): ' + str(key_missing))

    FP = re.compile(r"统一复核|降低上手门槛|可追溯流程|边界样本建议单独标注|减少重复确认成本|"
                    r"标准化，再批量|可复核输出|沿用模板逐项核对|形成标准复核清单|统一口径|"
                    r"快速复核|高频复用模板|在.{1,20}(业务|场景)里，优先把.{1,40}标准化后再执行|"
                    r"复用模板示例|保留复用模板")
    added_s = added_f = 0
    for s in slugs:
        e = dd['sports/' + s]
        sc = e.setdefault('scenarios', [])
        fa = e.setdefault('faqs', [])
        scen2, q2, a2 = D[s]
        if FP.search(scen2) or FP.search(q2) or FP.search(a2):
            raise SystemExit('套话命中 slug=%s' % s)
        if scen2 not in sc:
            sc.append(scen2); added_s += 1
        if not any(x.get('q') == q2 for x in fa):
            fa.append({'q': q2, 'a': a2}); added_f += 1

    json.dump(dd, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('OK 追加场景=%d 追加FAQ=%d  覆盖工具=%d' % (added_s, added_f, len(slugs)))

if __name__ == '__main__':
    main()

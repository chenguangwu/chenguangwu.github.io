def main():
    apply = '--apply' in sys.argv
    d = json.load(open(SRC, encoding='utf-8'))
    for k, v in CONTENT.items():
        assert k in d, f'缺失条目 {k}'
        sc, ex, fa = v['scenarios'], v['examples'], v['faqs']
        assert len(sc) == 3 and len(ex) == 2 and len(fa) == 2, f'{k} 结构不符'
        # 算例须含数字
        import re
        assert any(re.search(r'\d', x['body']) for x in ex), f'{k} 缺数字算例'
        d[k] = v
        print('更新', k)
    if apply:
        json.dump(d, open(SRC, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('已写入', SRC)
    else:
        print('（dry-run，未写入；加 --apply 写入）')

if __name__ == '__main__':
    main()

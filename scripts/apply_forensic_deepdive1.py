def main():
    apply = '--apply' in sys.argv
    d = json.load(open(SRC, encoding='utf-8'))
    for k, v in CONTENT.items():
        assert k in d, 'missing key %s' % k
        sc = len(v['scenarios']); ex = len(v['examples']); fa = len(v['faqs'])
        assert sc >= 3 and ex >= 2 and fa >= 2, '结构不足 %s' % k
        if apply:
            d[k] = v
            print('写入', k)
        else:
            print('预览', k, '场景%d 例%d FAQ%d' % (sc, ex, fa))
    if apply:
        json.dump(d, open(SRC, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('已写入 %d 条' % len(CONTENT))

if __name__ == '__main__':
    main()

def load():
    with open(JSON_PATH, encoding="utf-8") as f:
        return json.load(f)


def main():
    apply = "--apply" in sys.argv
    d = load()
    bad = []
    for slug, data in HVAC_DATA.items():
        key = "hvac/" + slug
        if key not in d:
            print("⚠  JSON 缺条目:", key)
            continue
        blob = json.dumps(data, ensure_ascii=False)
        if FP.search(blob):
            bad.append((slug, FP.findall(blob)))
        d[key]["title"] = data["title"]
        d[key]["scenarios"] = data["scenarios"]
        d[key]["examples"] = data["examples"]
        d[key]["faqs"] = data["faqs"]
    if bad:
        print("❌ 以下条目仍含检测词，已中止：")
        for slug, ms in bad:
            print("  ", slug, ms)
        return
    if apply:
        with open(JSON_PATH, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=1)
        print("✅ 已写入 %d 条 hvac deep-dive（弱泛化模板已替换为真实算例）" % len(HVAC_DATA))
    else:
        print("✅ dry-run：%d 条均无检测词，可 --apply" % len(HVAC_DATA))


if __name__ == "__main__":
    main()

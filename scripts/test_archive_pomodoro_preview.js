#!/usr/bin/env node
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { JSDOM } = require('jsdom');
const page = fs.readFileSync(path.join(__dirname, '../tools/edu/exam-study-planner.html'), 'utf8');
const script = [...page.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1]).find(s => s.includes('let pomo ='));
const dom = new JSDOM(page.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, ''), { runScripts: 'dangerously', url: 'https://example.test/' });
const { window } = dom;
const doc = window.document;
window.ToolBox = { initToolTheme() {}, showToast() {}, escHtml: String };
window.i18nText = () => '';
window.eval(script);
const set = (id, value) => { const el = doc.getElementById(id); el.value = value; el.dispatchEvent(new window.Event('input', { bubbles: true })); };
set('focus-mins', '30');
assert.strictEqual(doc.getElementById('pomo-time').textContent, '30:00', '待开始时输入应更新计时器');
set('break-mins', '7');
set('target-rounds', '3');
assert(doc.getElementById('pomo-plan').textContent.includes('30'));
assert(doc.getElementById('pomo-plan').textContent.includes('7'));
assert.strictEqual(doc.getElementById('pomo-target').textContent, '3');
window.togglePomo();
window.tickPomo();
const before = doc.getElementById('pomo-time').textContent;
set('focus-mins', '20');
assert.strictEqual(doc.getElementById('pomo-time').textContent, before, '运行中不得重置计时器');
window.togglePomo();
set('focus-mins', '15');
assert.strictEqual(doc.getElementById('pomo-time').textContent, before, '暂停时不得重置计时器');
window.resetPomo();
assert.strictEqual(doc.getElementById('pomo-time').textContent, '15:00');
console.log('PASS 番茄钟实时预览及暂停保护');
window.close();

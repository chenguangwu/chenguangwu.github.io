    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    if not (a.dry_run or a.apply):
        print("请指定 --dry-run 或 --apply")
        return 2

    dd = json.load(open(DD, encoding="utf-8"))
    added = 0
    for key, fields in G.items():
        if key not in dd:
            print("!! 缺条目:", key)
            continue
        for k, v in fields.items():
            dd[key][k] = v
        added += 1
    print(f"待写入工具数: {added}；字段: " + " ".join(sorted({k for f in G.values() for k in f})))

    if a.dry_run:
        for key in list(G)[:3]:
            print("\n预览", key, "=>", json.dumps({k: G[key][k] for k in ("features", "steps", "tips")}, ensure_ascii=False)[:400])
        return 0

    json.dump(dd, open(DD, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("已写入 content_deepdive.json")
    return 0


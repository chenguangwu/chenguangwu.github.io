def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    if not (args.dry_run or args.apply):
        ap.error("需指定 --dry-run 或 --apply")

    dd = json.load(open(DD, encoding="utf-8"))
    miss = [s for s in EX if ("finance/" + s) not in dd]
    print(f"目标 {len(EX)} 个；条目缺失 {len(miss)} {miss}")

    PATS = ["的反例复核", "基准复核", "示例"]
    changed = 0
    for slug, exs in EX.items():
        k = "finance/" + slug
        if k not in dd:
            continue
        old = json.dumps(dd[k].get("examples"), ensure_ascii=False)
        # 幂等：已真实（不含三类模板）则跳过
        if any(p in old for p in PATS) or "使用页面默认值" in old or "用一组整齐的基准数值" in old \
                or "先输入一个格式正确的" in old or "输入一段包含中英文" in old or "用页面默认参数生成" in old:
            dd[k]["examples"] = [{"title": t, "body": b} for t, b in exs]
            changed += 1
    print(f"将被真实化：{changed} 个")

    if args.dry_run:
        for slug in list(EX)[:2]:
            k = "finance/" + slug
            if k in dd:
                print("  预览", slug, json.dumps(dd[k]["examples"], ensure_ascii=False)[:130])
        return 0

    json.dump(dd, open(DD, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("已写入", DD)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

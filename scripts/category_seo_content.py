def faq_ld(sec, count, base_url='https://chenguangwu.github.io'):
    """生成 FAQPage 结构化数据脚本标签；无 FAQ 返回空字符串。"""
    import json as _json
    faq = sec.get('faq', [])
    if not faq:
        return ''
    items = []
    for q, a in faq:
        if '%d' in q:
            q = q % count
        if '%d' in a:
            a = a % count
        items.append({
            '@type': 'Question',
            'name': q,
            'acceptedAnswer': {'@type': 'Answer', 'text': a},
        })
    data = {'@context': 'https://schema.org', '@type': 'FAQPage', 'mainEntity': items}
    return ('<script type="application/ld+json">\n%s\n</script>\n'
            % _json.dumps(data, ensure_ascii=False))



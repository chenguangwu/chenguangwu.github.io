def main():
    apply = '--apply' in sys.argv
    d = json.load(open(JSON_PATH, encoding='utf-8'))
    if not apply:
        # dry-run：检查键存在且当前为空
        for k in DATA:
            cur = d.get(k)
            print('dry: %s 当前=%s' % (k, '空{}' if (isinstance(cur, dict) and not cur) else type(cur).__name__))
        print('dry-run 通过，加 --apply 写入')
        return
    for k, v in DATA.items():
        d[k] = v
    json.dump(d, open(JSON_PATH, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print('已写入 %d 条 history deep-dive' % len(DATA))


if __name__ == '__main__':
    main()

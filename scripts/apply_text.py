def main():
    with open(DD, encoding="utf-8") as f:
        d = json.load(f)
    before = len(d)
    assert before == EXPECT, f"键数异常: 期望 {EXPECT}, 实际 {before}"
    missing = [k for k in NEW if k not in d]
    assert not missing, f"缺少键: {missing}"
    for k, v in NEW.items():
        d[k] = v
    after = len(d)
    assert after == EXPECT, f"写入后键数异常: {after}"
    # 自检: 不得残留任何占位指纹
    import sys
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from detect_placeholders import hits
    for k in NEW:
        blob = json.dumps(d[k], ensure_ascii=False)
        h = hits(blob)
        assert not h, f"{k} 仍含占位指纹: {h}"
    with open(DD, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"OK: text 11 条 deep-dive 已真实化，键数守恒 = {after}")


if __name__ == "__main__":
    main()

def load():
    with open(JSON_PATH, encoding='utf-8') as f:
        return json.load(f)


def save(d):
    # 仓库规范：indent=1 + 冒号后空格，避免全文件重排噪音
    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=1, separators=(',', ': '))
        f.write('\n')


def main():
    d = load()
    before = len(d)
    for key, entry in REPL.items():
        assert key in d, f'缺失键 {key}'
        d[key] = entry
    after = len(d)
    assert after == before, f'键数变化: {before} -> {after}'

    # 占位自检：仅针对本分类 7 键
    for key in ONLY_KEYS:
        blob = json.dumps(d[key], ensure_ascii=False)
        assert not GEN.search(blob), f'{key} 仍存在 STY3/GEN 占位!'

    save(d)
    print(f'OK: printing 7 条 deep-dive 已真实化，键数守恒 = {after}')


if __name__ == '__main__':
    main()

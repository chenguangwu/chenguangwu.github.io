def main():
    with open(JSON_PATH, encoding='utf-8') as f:
        d = json.load(f)
    before = len(d)
    replaced = 0
    for k, v in DATA.items():
        if k not in d:
            print('WARN: key not found, skip:', k)
            continue
        d[k] = v
        replaced += 1
    after = len(d)
    assert after == before, '键数变化！%d -> %d' % (before, after)
    assert after == 5022, '键数不等于 5022：%d' % after
    assert replaced == len(DATA), '替换数不符：%d/%d' % (replaced, len(DATA))

    # 占位自检
    import re
    GEN = re.compile(r'当你在\w+相关场景中|在对应的输入框或选项中填写|快速复核|统一输入单位与口径|标准化后再执行对比|为何要生成可复核输出')
    hits = 0
    for k in DATA:
        blob = json.dumps(d[k], ensure_ascii=False)
        if GEN.search(blob):
            hits += 1
            print('FAIL 占位命中:', k)
    assert hits == 0, '仍有 %d 条命中占位' % hits

    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=1, separators=(',', ': '))
        f.write('\n')

    print('OK: sales %d 条 deep-dive 已真实化，键数守恒 = %d' % (replaced, after))


if __name__ == '__main__':
    main()

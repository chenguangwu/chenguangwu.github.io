    with open(SRC, encoding="utf-8") as f:
        d = json.load(f)
    cnt = 0
    for k, v in DATA.items():
        if k not in d:
            print("WARN 缺失 key:", k)
            continue
        d[k]["summary"] = v["summary"]
        d[k]["scenarios"] = v["scenarios"]
        d[k]["examples"] = v["examples"]
        d[k]["faqs"] = v["faqs"]

def count_cliche(d):
    txt = json.dumps(d, ensure_ascii=False)
    return sum(txt.count(c) for c in CLICHE)


def main():
    with open(SRC, encoding="utf-8") as f:
        data = json.load(f)
    before_total = len(data)
    before_cliche = count_cliche({k: data[k] for k in NEW})

    for k, v in NEW.items():
        assert k in data, "missing key: " + k
        data[k] = v

    after_total = len(data)
    after_cliche = count_cliche({k: data[k] for k in NEW})

    assert after_total == before_total == 5022, "key count drift: %d" % after_total
    assert before_cliche >= 5, "expected >=5 residual cliche before, got %d" % before_cliche
    assert after_cliche == 0, "residual cliche after: %d" % after_cliche

    with open(SRC, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1, separators=(",", ": "))

    print("updated keys: %d / total keys: %d / residual cliche (before/after): %d / %d / %s"
          % (len(NEW), after_total, before_cliche, after_cliche, "OK" if after_cliche == 0 else "FAIL"))


if __name__ == "__main__":
    main()

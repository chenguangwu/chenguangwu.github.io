missing = [k for k in NEW if k not in data]
if missing:
    print("ERROR: 以下键在 JSON 中不存在:", missing)
    sys.exit(1)

for k, content in NEW.items():
    orig = data[k]
    title = orig.get("title", "")
    new_entry = {
        "title": title,
        "scenarios": content["scenarios"],
        "examples": content["examples"],
        "faqs": content["faqs"],
    }
    blob = json.dumps(new_entry, ensure_ascii=False)
    if PLACEHOLDER.search(blob):
        print("ERROR: 占位指纹泄漏于", k)
        sys.exit(1)
    assert len(new_entry["scenarios"]) == 3, f"{k} scenarios 数量异常"
    assert len(new_entry["examples"]) == 2, f"{k} examples 数量异常"
    assert len(new_entry["faqs"]) == 2, f"{k} faqs 数量异常"
    data[k] = new_entry

after_keys = set(data.keys())
assert before_keys == after_keys, "ERROR: 键数不守恒!"

with open(PATH, "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=1)


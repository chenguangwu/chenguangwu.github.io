def main():
    with open(JSON_PATH, encoding='utf-8') as f:
        data = json.load(f)

    before = len(data)
    assert before == EXPECT_KEYS, f'键数不符：{before} != {EXPECT_KEYS}'

    for k in NEW:
        assert k in data, f'键缺失：{k}'

    for k, v in NEW.items():
        data[k] = v

    after = len(data)
    assert after == EXPECT_KEYS, f'写入后键数不符：{after} != {EXPECT_KEYS}'

    bad = 0
    for k in NEW:
        s = json.dumps(data[k], ensure_ascii=False)
        hits = BAD_PAT.findall(s)
        if hits:
            bad += 1
            print(f'  !! {k} 仍有占位：{hits[:3]}')
    assert bad == 0, f'{bad} 个键仍含占位指纹'

    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1, separators=(',', ': '))

    print(f'OK 键数守恒 {before} -> {after}；tunnel 5 键真实化，占位 {bad}')


if __name__ == '__main__':
    main()

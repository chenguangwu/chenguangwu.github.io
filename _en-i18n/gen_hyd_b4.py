def build(slug, en_list):
    path = os.path.join(WORK, slug + '.json')
    wj = json.load(open(path, encoding='utf-8'))
    items = wj.get('items', [])
    if len(en_list) != len(items):
        print('!! %s length mismatch %d vs %d' % (slug, len(en_list), len(items))); sys.exit(1)
    mp = {}
    for it, en in zip(items, en_list):
        if not en or not isinstance(en, str):
            print('!! %s empty translation' % slug); sys.exit(1)
        if CJK.search(en) or CNP.search(en):
            print('!! %s CJK/CNP violation: %s' % (slug, en[:60])); sys.exit(1)
        z = (it.get('zh') or '').strip()
        if z and z not in mp:
            mp[z] = en
        if it.get('src_diff') and it.get('zh_src'):
            zs = (it['zh_src'] or '').strip()
            if zs and zs not in mp:
                mp[zs] = en
    return mp

def write(slug, mp):
    os.makedirs(OUT, exist_ok=True)
    wj = json.load(open(os.path.join(WORK, slug + '.json'), encoding='utf-8'))
    name = wj.get('name', slug)
    out = {'slug': slug, 'industry': 'hydraulic', 'name': name, 'map': mp}
    p = os.path.join(OUT, slug + '.json')
    json.dump(out, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    open(p, 'a', encoding='utf-8').write('\n')
    print('WROTE %s (+%d)' % (slug, len(mp)))

if __name__ == '__main__':
    for slug, en_list in EN.items():
        write(slug, build(slug, en_list))
    print('gen_hyd_b4 done')

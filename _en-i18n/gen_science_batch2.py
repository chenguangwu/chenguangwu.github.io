def merge_dict(path, add):
    if not os.path.exists(path):
        print('!! missing dict', path); return 0
    d = json.load(io.open(path, encoding='utf-8'))
    mp = d.setdefault('map', {})
    n0 = len(mp)
    for k, v in add.items():
        if k not in mp:
            mp[k] = v
        elif mp[k] != v:
            print('!conflict', os.path.basename(path), repr(k), '|have:', repr(mp[k]), '|new:', repr(v))
    with io.open(path, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.write('\n')
    return len(mp) - n0


def main():
    tot = 0
    for slug, mp in PER.items():
        p = 'i18n/tools/en/science/%s.json' % slug
        n = merge_dict(p, mp)
        tot += n
        print('%-28s +%d  (src %d)' % (slug, n, len(mp)))
    print('per-tool added total', tot)
    bad = []
    for p in ['i18n/tools/en/science/%s.json' % s for s in PER]:
        d = json.load(io.open(p, encoding='utf-8'))
        for k, v in d.get('map', {}).items():
            if isinstance(v, str) and CJK.search(v):
                bad.append((os.path.basename(p), k, v))
    print('CJK values:', len(bad))
    for b in bad[:20]: print('  ', b)


if __name__ == '__main__':
    main()

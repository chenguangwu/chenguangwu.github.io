def merge_dict(path, add):
    if not os.path.exists(path):
        print('!! missing dict', path); return 0
    d = json.load(io.open(path, encoding='utf-8'))
    mp = d.setdefault('map', {})
    n0 = len(mp)
    conflict = 0
    for k, v in add.items():
        if k not in mp:
            mp[k] = v
        elif mp[k] != v:
            conflict += 1
            print('!conflict', os.path.basename(path), repr(k), '|have:', repr(mp[k]), '|new:', repr(v))
    with io.open(path, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.write('\n')
    return len(mp) - n0, conflict



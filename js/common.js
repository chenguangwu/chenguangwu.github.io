function validateNumberInput(el){
  if(!el || el.type !== 'number') return true;
  var val = parseFloat(el.value);
  if(el.value !== '' && isNaN(val)){
    markInvalid(el, i18nText('validate.number'));
    return false;
  }
  clearInvalid(el);
  return true;
}


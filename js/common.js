function copyText(text, successMsg){
  successMsg = resolveUiText(successMsg, i18nText('toast.copy_success'));
  if(navigator.clipboard && navigator.clipboard.writeText){
    return navigator.clipboard.writeText(text).then(function(){ showToast(successMsg); }).catch(function(){ fallbackCopy(text, successMsg); });
  } else {
    fallbackCopy(text, successMsg);
    return Promise.resolve();
  }
}
function copyToClipboard(text, successMsg){
  return copyText(text, successMsg);
}

function fallbackCopy(text, successMsg){
  successMsg = resolveUiText(successMsg, i18nText('toast.copy_success'));
  var ta = document.createElement('textarea');
  ta.value = text;
  ta.style.cssText = 'position:fixed;left:-9999px;opacity:0;';
  document.body.appendChild(ta);
  ta.select();
  try { document.execCommand('copy'); showToast(successMsg || i18nText('toast.copy_success')); }
  catch(e){ showToast(i18nText('toast.copy_failed'), 'error'); prompt(i18nText('toast.copy_prompt'), text); }
  ta.remove();
}

function copyFromElement(elId, successMsg){
  var el = document.getElementById(elId);
  if(!el){ showToast(i18nText('toast.element_not_found'), 'error'); return; }
  var text = el.dataset.copyValue || el.value || el.textContent || el.innerText;
  copyText(text.trim(), successMsg);
}

function downloadText(filename, content, mime){
  var blob = new Blob([content], {type: mime || 'text/plain;charset=utf-8'});
  var url = URL.createObjectURL(blob);
  var a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  if (window.ToolBox && ToolBox.Metrics) { var pp = (location.pathname || '').split('/').filter(Boolean); ToolBox.Metrics.track('download', { tool: pp[pp.length - 1], industry: pp.length >= 2 ? pp[pp.length - 2] : '' }); }
  setTimeout(function(){ URL.revokeObjectURL(url); a.remove(); }, 0);
}

function formatNumber(n, decimals){
  if(typeof n !== 'number' || isNaN(n)) return String(n);
  decimals = decimals != null ? decimals : 0;
  return n.toLocaleString('zh-CN', {minimumFractionDigits:decimals, maximumFractionDigits:decimals});
}


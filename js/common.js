// 结果格式化工具函数：千分位 + 指定小数位
global.fmtNum = function(n, digits){
  var num = parseFloat(n);
  if (isNaN(num)) return '';
  var d = (digits === undefined || digits === null) ? 2 : digits;
  try {
    return num.toLocaleString('zh-CN', { minimumFractionDigits: d, maximumFractionDigits: d });
  } catch(e){ return String(num); }
};


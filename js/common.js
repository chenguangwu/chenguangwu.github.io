  function normalizePath(path){
    if(!path) return '';
    var p = path.split('#')[0].split('?')[0];
    if(p.indexOf('/tools/') === -1) return '';
    var segs = p.split('/').filter(Boolean);
    var idx = segs.lastIndexOf('tools');
    if (idx === -1 || idx + 1 >= segs.length) return '';
    return segs[idx + 1];
  }


function toggleFavTool(){
  var url = getToolUrl();
  if(!url) return;
  var favs = getFavs();
  var i = favs.indexOf(url);
  if(i > -1){ favs.splice(i, 1); showToast(i18nText('toast.fav_removed')); }
  else { favs.push(url); showToast(i18nText('toast.fav_added')); }
  setFavs(favs);
  updateFavBtn();
}
function updateFavBtn(){
  var btn = document.querySelector('.fav-btn');
  if(!btn) return;
  var on = getFavs().indexOf(getToolUrl()) > -1;
  btn.textContent = on ? '❤️' : '🤍';
  btn.classList.toggle('active', on);
  btn.title = on ? i18nText('tool.fav_remove') : i18nText('tool.fav_add');
}
function isStandardToolUrl(url){
  if(!url) return false;
  var clean = String(url).split('?')[0].split('#')[0].trim();
  if (!clean || /^(https?:)?\/\//.test(clean) || /^mailto:|^javascript:/i.test(clean)) return false;
  clean = clean.replace(/^(\.\.\/)+/, '').replace(/^\.\//, '').replace(/^\/+/, '').replace(/^tools\//, '');
  if (!clean || /\/index(?:\.html)?$/i.test(clean)) return false;
  if (!/\.html$/i.test(clean)) return false;
  var parts = clean.replace(/^\/+/, '').split('/').filter(Boolean);
  if (parts.length !== 2) return false;
  if (!parts[0] || !parts[1]) return false;
  if (/^index(?:\.html)?$/i.test(parts[1])) return false;
  return true;
}

// 相关工具推荐：基于当前行业 + 用户行为（收藏/最近）排序，纯前端无数据时退化为同行业推荐
function getToolIndustry(){
  try {
    var m = document.querySelector('meta[name="toolbox"]');
    if(!m) return null;
    var c = m.getAttribute('content') || '';
    var mm = c.match(/industry=([^,]+)/);
    return mm ? mm[1] : null;
  } catch(e){ return null; }
}
function renderRelatedTools(){
  if(document.querySelector('.related-tools')) return;
  var ind = getToolIndustry();
  if(!ind) return;
  var relatedTitle = i18nText('tool.related', '🔗 相关工具');
  var loadingText = i18nText('common.loading', '加载中…');
  var cur = (location.pathname || '').replace(/^\/+/, '');
  var wrap = document.createElement('div');
  wrap.className = 'related-tools card';
  wrap.style.marginTop = '20px';
  wrap.innerHTML = '<h3 class="related-tools-title" style="font-size:15px;margin-bottom:12px;">' +
    relatedTitle +
    '</h3><div class="rt-loading" style="font-size:13px;color:var(--text-muted)">' +
    loadingText +
    '</div>';
  var container = document.querySelector('.container');
  if(!container) return;
  container.appendChild(wrap);
  fetch('../../json/industry-' + ind + '.json')
    .then(function(r){ return r.ok ? r.json() : null; })
    .then(function(list){
      if(!list || !list.length){ wrap.style.display = 'none'; return; }
      var others = list.filter(function(t){ return isStandardToolUrl(t.url) && t.url !== cur; });
      // 用户行为加权：收藏/最近用过的同行业工具优先
      var used = {};
      try { getRecents().concat(getFavs()).forEach(function(u){ used[u] = true; }); } catch(e){}
      others.sort(function(a, b){ return (used[b.url] ? 1 : 0) - (used[a.url] ? 1 : 0); });
      var top = others.slice(0, 8);
      if(!top.length){ wrap.style.display = 'none'; return; }
      wrap.innerHTML = '<h3 class="related-tools-title" style="font-size:15px;margin-bottom:12px;">' +
        relatedTitle +
        '</h3><div class="rt-grid">' +
        top.map(function(t){
          var n = isZh ? (t.name || t.desc || t.url) : (t.en || t.ed || t.name || t.desc || t.url);
          var d = isZh ? (t.desc || t.name || t.url) : (t.ed || t.desc || t.name || t.url);
          if (n === d) {
            d = '';
          }
          return '<a class="rt-item" href="../../' + escHtml(t.url) + '">' +
            '<span class="rt-ico">' + escHtml(t.icon || '🔧') + '</span>' +
            '<span class="rt-info"><span class="rt-name">' + escHtml(n) + '</span><span class="rt-desc">' + escHtml(d || '') + '</span></span></a>';
        }).join('') + '</div>';
    })
    .catch(function(){ wrap.style.display = 'none'; });
}

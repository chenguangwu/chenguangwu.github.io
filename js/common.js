function resolveCanvasColor(value, fallback){
  var color=String(value||'').trim();
  var variable=color.match(/^var\((--[\w-]+)\)$/);
  if(variable){
    color=getComputedStyle(document.documentElement).getPropertyValue(variable[1]).trim();
  }
  return color||fallback;
}

function canvasColorWithAlpha(value, fallback, alpha){
  var color=resolveCanvasColor(value,fallback);
  var hex=color.match(/^#([0-9a-f]{6})$/i);
  if(hex){
    var n=parseInt(hex[1],16);
    return 'rgba('+(n>>16)+','+((n>>8)&255)+','+(n&255)+','+alpha+')';
  }
  var shortHex=color.match(/^#([0-9a-f]{3})$/i);
  if(shortHex){
    return canvasColorWithAlpha('#'+shortHex[1].split('').map(function(c){return c+c;}).join(''),fallback,alpha);
  }
  var rgb=color.match(/^rgb\(([^)]+)\)$/i);
  if(rgb) return 'rgba('+rgb[1]+','+alpha+')';
  return color;
}


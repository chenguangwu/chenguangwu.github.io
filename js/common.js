function buildDynRes(){
  var keys = Object.keys(CN_DYN_TEXT_MAP);
  keys.sort(function(a, b){
    var la = a.replace(/\{\d+\}/g, '').length, lb = b.replace(/\{\d+\}/g, '').length;
    if (lb !== la) return lb - la;
    return b.length - a.length;
  });
  var arr = [];
  for (var i = 0; i < keys.length; i++){
    var zh = keys[i];
    var re = '^' + zh.replace(/\{(\d+)\}/g, '\u0001$1\u0001').replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\u0001(\d+)\u0001/g, '(.*?)') + '$';
    arr.push({ re: new RegExp(re), en: CN_DYN_TEXT_MAP[zh] });
  }
  return arr;
}

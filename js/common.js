// 数字型文本框识别关键词（用于判断 text 输入框是否为数字输入）
var NUM_HINT_RE = /数字|数值|金额|单价|数量|长度|宽度|高度|重量|体积|温度|时间|年份|百分比|利率|费用|价格|面积|距离|速度|频率|电压|电流|功率|能量|容量|人数|次数|系数|比例|分数|半径|直径|边长|年龄|天数|月数|年数|公里|米|千克|克|吨|升|毫升|小时|分钟|秒|元|万|亿/;
function enhanceNumberInputs(){
  try {
    document.querySelectorAll('input[type="text"]').forEach(function(inp){
      if (!inp.getAttribute('inputmode') && NUM_HINT_RE.test(inp.placeholder || '')) {
        inp.setAttribute('inputmode', 'decimal');
        inp.setAttribute('pattern', '[0-9.\\-]*');
      }
    });
    document.querySelectorAll('input[inputmode="decimal"], input[inputmode="numeric"]').forEach(function(inp){
      if (inp.__numGuard) return;
      inp.__numGuard = true;
      inp.addEventListener('input', function(){
        // 非法字符阻止（保留数字、小数点、负号）
        var cleaned = inp.value.replace(/[^0-9.\-]/g, '');
        if (cleaned !== inp.value) inp.value = cleaned;
        if (inp.getAttribute('data-invalid')) { inp.style.borderColor = ''; inp.removeAttribute('data-invalid'); }
      });
      inp.addEventListener('blur', function(){
        var v = inp.value.trim();
        if (v === '' || isNaN(parseFloat(v))) {
          inp.style.borderColor = '#EF4444';
          inp.setAttribute('data-invalid', '1');
        } else {
          inp.style.borderColor = '';
          inp.removeAttribute('data-invalid');
        }
      });
    });
  } catch(e){}
}
document.addEventListener('DOMContentLoaded', enhanceNumberInputs);

// B5-11 Ref-card 与卡片化交互元素增强（仅对存在点击行为或明确卡片语义生效）
// 目的：卡片真实可点时，补齐可访问语义与键盘触发，减少 dead click。
(function(){
  var ENHANCED_ATTR = 'data-tb-refcard-enhanced';
  var CARDLIKE_SELECTOR = '.ref-card,.nrs-point,.type-chip,.area-chip,.tool-intro-header,.history-item,.patient-item,.criteria-box,.grade-card,.q-opt';

  function isCardLikeInteractive(node){
    if (!node || node.nodeType !== 1 || !node.classList || !node.matches) return false;
    if (node.matches(CARDLIKE_SELECTOR)) return true;
    return false;
  }

  function ensureRefCardInteractive(node){
    if (!node || node.nodeType !== 1 || !node.classList) return;
    if (!isCardLikeInteractive(node)) return;

    if (node.getAttribute(ENHANCED_ATTR)) return;

    var hasOnAttr = !!node.getAttribute('onclick');
    var hasOnProp = typeof node.onclick === 'function';
    if (!hasOnAttr && !hasOnProp) return;

    if (!node.getAttribute('role')) node.setAttribute('role', 'button');
    if (!node.hasAttribute('tabindex')) node.setAttribute('tabindex', '0');
    if (!node.hasAttribute('aria-pressed')) node.setAttribute('aria-pressed', node.classList.contains('active') ? 'true' : 'false');
    if (!node.style.cursor) node.style.cursor = 'pointer';

    node.addEventListener('keydown', function(event){
      if (event.key === 'Enter' || event.key === ' ') {
        event.preventDefault();
        node.click();
      }
    });

    node.setAttribute(ENHANCED_ATTR, '1');
  }

  function scanRefCards(){
    document.querySelectorAll(CARDLIKE_SELECTOR).forEach(ensureRefCardInteractive);
  }

  if (!Element.prototype.__tbRefCardPatched) {
    var originalAddEventListener = Element.prototype.addEventListener;
    Element.prototype.addEventListener = function(type, listener, options){
      if (type === 'click' && isCardLikeInteractive(this)) {
        var target = this;
        setTimeout(function(){ ensureRefCardInteractive(target); }, 0);
      }
      return originalAddEventListener.call(this, type, listener, options);
    };
    Element.prototype.__tbRefCardPatched = true;
  }

  document.addEventListener('DOMContentLoaded', function(){
    scanRefCards();
    setTimeout(scanRefCards, 120);
    setTimeout(scanRefCards, 360);
    setTimeout(scanRefCards, 900);
  });
})();


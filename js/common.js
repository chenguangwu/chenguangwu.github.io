function extractNumbers(text){
  var m = (text || '').match(/-?\d+(?:\.\d+)?/g);
  if(!m) return [];
  return m.map(function(x){ return parseFloat(x); }).filter(function(n){ return !isNaN(n); });
}
// 自动图表：结果区声明 data-viz，从文本实时提取数值渲染（无需改写各工具 calc）
function initResultViz(){
  var boxes = document.querySelectorAll('[data-viz]');
  boxes.forEach(function(box){
    // 图表画布作为结果区的兄弟节点插入（避免 calc() 重写 innerHTML 时把画布一起清掉）
    var canvas = box.parentNode && box.parentNode.querySelector(':scope > canvas.viz-canvas[data-for="'+ (box.id||'') +'"]');
    if(!canvas){
      canvas = document.createElement('canvas');
      canvas.className = 'viz-canvas';
      canvas.setAttribute('data-chart', box.getAttribute('data-viz'));
      canvas.setAttribute('data-for', box.id || '');
      if(box.parentNode) box.parentNode.insertBefore(canvas, box.nextSibling);
      else box.appendChild(canvas);
    }
    ensureChartLib(function(){
      function draw(){
        var nums = extractNumbers(box.textContent || '');
        if(!nums.length) return;
        var type = box.getAttribute('data-viz');
        var min = parseFloat(box.getAttribute('data-min'));
        var max = parseFloat(box.getAttribute('data-max'));
        var unit = box.getAttribute('data-unit') || '';
        var labels = (box.getAttribute('data-labels') || '').split(',').filter(Boolean);
        if(type === 'gauge'){
          canvas.setAttribute('data-chart-cfg', JSON.stringify({
            value: nums[0],
            min: isNaN(min) ? 0 : min,
            max: isNaN(max) ? Math.max(nums[0]*1.2, 1) : max,
            unit: unit
          }));
        } else if(type === 'bar'){
          canvas.setAttribute('data-chart-cfg', JSON.stringify({
            labels: labels.length ? labels : nums.map(function(_,i){ return '值'+(i+1); }),
            values: nums
          }));
        } else if(type === 'line'){
          canvas.setAttribute('data-chart-cfg', JSON.stringify({
            labels: labels.length ? labels : nums.map(function(_,i){ return (i+1); }),
            values: nums
          }));
        }
        renderVizCanvas(canvas);
      }
      draw();
      if('MutationObserver' in window){
        new MutationObserver(draw).observe(box, {childList:true, subtree:true, characterData:true});
      }
    });
  });
}
function ensureCharts(){
  var explicit = document.querySelectorAll('canvas[data-chart]');
  if(explicit.length){ ensureChartLib(function(){ explicit.forEach(renderVizCanvas); }); }
  initResultViz();
}
document.addEventListener('DOMContentLoaded', ensureCharts);

